function localBaseFor(code: string): Record<string, string> {
  const primary = primaryLanguageCode(code);
  if (primary === 'tr') {
    return { ...FALLBACK_TRANSLATIONS, ...LOCAL_TRANSLATIONS_TR };
  }
  const overlay = localOverlay(primary);
  return Object.keys(overlay).length
    ? { ...FALLBACK_TRANSLATIONS, ...overlay }
    : FALLBACK_TRANSLATIONS;
}

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [status, setStatus] = useState<LocaleStatus>('loading');
  const [error, setError] = useState<string | null>(null);
  const [languageCode, setLanguageCode] = useState('en');
  const [languages, setLanguages] = useState<LanguageDto[]>(FALLBACK_LANGUAGES);
  const [translations, setTranslations] = useState<Record<string, string>>(
    FALLBACK_TRANSLATIONS,
  );
  const [device, setDevice] = useState<DeviceState | null>(null);

  const applyTranslationResponse = useCallback((code: string, response: {
    LanguageCode?: string;
    Translations?: Record<string, string>;
  }) => {
    const nextCode = response.LanguageCode || code;
    setTranslations({
      ...localBaseFor(nextCode),
      ...(response.Translations ?? {}),
      ...(primaryLanguageCode(nextCode) === 'tr' ? LOCAL_TRANSLATIONS_TR : {}),
      ...localOverlay(nextCode),
    });
    setApiLanguageCode(nextCode);
    setLanguageCode(nextCode);
    syncRtl(nextCode);
  }, []);

  const loadTranslations = useCallback(async (code: string) => {
    setApiLanguageCode(code);
    const pack = await readLocalePack(code);
    if (pack?.translations && isLocalePackFresh(pack)) {
      applyTranslationResponse(code, pack.translations);
      return;
    }
    if (pack?.translations) {
      applyTranslationResponse(code, pack.translations);
    }
    const response = await fetchTranslationsByCode(code);
    applyTranslationResponse(code, response);
    void writeLocalePack({
      code: response.LanguageCode || code,
      translations: response,
      languages: pack?.languages,
    });
  }, [applyTranslationResponse]);

  const bootstrap = useCallback(async () => {
    setError(null);

    try {
      const restoredLanguage = await hydrateApiLanguageCode();
      const info = await getDeviceLaunchInfo();
      console.log('[DeviceInfo]', info);
      if (!restoredLanguage) {
        setApiLanguageCode(info.language);
      }
      const localCode = getApiLanguageCode();
      setLanguageCode(localCode);
      setTranslations(localBaseFor(localCode));
      syncRtl(localCode);
    } catch (localErr) {
      console.warn('[Locale] local hydrate failed', localErr);
    }
    // Unblock splash / auth immediately — bundled copy is enough to enter.
    setStatus('ready');

    try {
      const info = await getDeviceLaunchInfo();
      const theme =
        info.colorScheme === 'unspecified' ? 'light' : info.colorScheme;

      const pushToken = await getStoredPushToken();
      const localePack = await readLocalePack(info.language);
      if (localePack?.languages?.length) {
        setLanguages(mergeLanguages(localePack.languages));
      }
      const [deviceResponse, languagesResponse] = await Promise.all([
        bootstrapDevice({
          DeviceUniqueId: info.uniqueId,
          Platform: info.platform,
          OsVersion: info.osVersion,
          LanguageCode: info.language,
          CultureCode: info.cultureCode,
          Theme: theme,
          PushToken: pushToken,
        }),
        localePack?.languages?.length && isLocalePackFresh(localePack)
          ? Promise.resolve({
              GetAllLanguagesQueryCommonObject: localePack.languages,
            })
          : fetchLanguages(),
      ]);

      const nextDevice: DeviceState = {
        id: deviceResponse.Id,
        uniqueId: deviceResponse.DeviceUniqueId,
        languageCode: deviceResponse.LanguageCode,
        cultureCode: deviceResponse.CultureCode ?? null,
        theme: deviceResponse.Theme,
        userId: deviceResponse.UserId ?? null,
        isNew: deviceResponse.IsNew,
      };

      setDevice(nextDevice);
      const nextLanguages = mergeLanguages(
        languagesResponse.GetAllLanguagesQueryCommonObject,
      );
      setLanguages(nextLanguages);
      await loadTranslations(nextDevice.languageCode);
      void writeLocalePack({
        code: nextDevice.languageCode,
        languages: nextLanguages,
      });
    } catch (err) {
      const message =
        err instanceof Error ? err.message : 'Failed to bootstrap locale';
      console.warn('[Locale] bootstrap failed', err);
      setLanguages(FALLBACK_LANGUAGES);
      setError(message);
    }
  }, [loadTranslations]);

  useEffect(() => {
    bootstrap();
  }, [bootstrap]);

  const setLanguage = useCallback(
    async (code: string) => {
      setApiLanguageCode(code);
      setLanguageCode(code);
      setTranslations(localBaseFor(code));
      syncRtl(code);

      try {
        if (device?.uniqueId) {
          const updated = await updateDeviceLanguage({
            DeviceUniqueId: device.uniqueId,
            LanguageCode: code,
          });

          setDevice(prev =>
            prev
              ? {
                  ...prev,
                  languageCode: updated.LanguageCode,
                  cultureCode: updated.CultureCode ?? null,
                }
              : prev,
          );
          await loadTranslations(updated.LanguageCode);
          return;
        }

        await loadTranslations(code);
      } catch (err) {
        console.warn('[Locale] setLanguage failed, keeping local code', err);
      }
    },
    [device?.uniqueId, loadTranslations],
  );

  const bindUser = useCallback(
    async (userId: number) => {
      const info = await getDeviceLaunchInfo();
      const uniqueId = device?.uniqueId || info.uniqueId;
      if (!uniqueId) {
        return;
      }

      // Ensure a device row exists (e.g. after DB wipe while app stayed in memory).
      try {
        await bootstrapDevice({
          DeviceUniqueId: uniqueId,
          Platform: info.platform,
          OsVersion: info.osVersion,
          LanguageCode: device?.languageCode || info.language,
          CultureCode: device?.cultureCode || info.cultureCode,
          Theme: device?.theme || (info.colorScheme === 'dark' ? 'dark' : 'light'),
          PushToken: await getStoredPushToken(),
        });
      } catch (bootstrapError) {
        console.warn('[Locale] bootstrap before bind failed', bootstrapError);
      }

      const bound = await bindDeviceUser({
        DeviceUniqueId: uniqueId,
        UserId: userId,
      });

      setDevice(prev =>
        prev
          ? {
              ...prev,
              uniqueId,
              userId: bound.UserId ?? userId,
            }
          : {
              id: bound.Id,
              uniqueId,
              languageCode: info.language.split(/[-_]/)[0] || 'en',
              cultureCode: info.cultureCode,
              theme: info.colorScheme === 'dark' ? 'dark' : 'light',
              userId: bound.UserId ?? userId,
              isNew: false,
            },
      );
    },
    [device],
  );

  const t = useCallback(
    (key: string, fallback?: string) =>
      translations[key] ?? fallback ?? FALLBACK_TRANSLATIONS[key] ?? key,
    [translations],
  );

  const isRtl = primaryLanguageCode(languageCode) === 'ar';

  const value = useMemo<LocaleContextValue>(
    () => ({
      status,
      error,
      languageCode,
      languages,
      translations,
      device,
      isRtl,
      t,
      setLanguage,
      bindUser,
      refresh: bootstrap,
    }),
    [
      status,
      error,
      languageCode,
      languages,
      translations,
      device,
      isRtl,
      t,
      setLanguage,
      bindUser,
      bootstrap,
    ],
  );

  return (
    <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
  );
}

export function useLocale(): LocaleContextValue {
  const ctx = useContext(LocaleContext);
  if (!ctx) {
    throw new Error('useLocale must be used inside a <LocaleProvider />');
  }
  return ctx;
}
